using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Nodo.HallSchedule.Domain;

namespace Nodo.HallSchedule.Infrastructure.Persistence.Configurations;

internal sealed class ScheduleBlockConfiguration : IEntityTypeConfiguration<ScheduleBlock>
{
    public void Configure(EntityTypeBuilder<ScheduleBlock> builder)
    {
        builder.ToTable("schedule_blocks", t =>
        {
            // INV-01 (also guards blocks): whole hours between 1 and 8, same day.
            t.HasCheckConstraint("ck_schedule_blocks_inv01_duration",
                "end_time > start_time AND end_time - start_time BETWEEN interval '1 hour' AND interval '8 hours'");
            t.HasCheckConstraint("ck_schedule_blocks_same_day", "\"date\" = schedule_date");
        });

        builder.HasKey(x => x.Id);
        builder.Property(x => x.Id).HasConversion(id => id.Value, value => new ScheduleBlockId(value)).ValueGeneratedNever();
        builder.Property(x => x.EventId).HasConversion(id => id.Value, value => new EventId(value));
        builder.Property(x => x.Kind).HasConversion<string>().HasMaxLength(20);
        builder.Property(x => x.Status).HasConversion<string>().HasMaxLength(20);
        builder.Property(x => x.CreatedAtUtc);
        builder.Property(x => x.ReleasedAtUtc);
        builder.Ignore(x => x.IsActive);

        builder.ComplexProperty(x => x.Slot, slot =>
        {
            slot.Property(s => s.Date).HasColumnName("date");
            slot.Property(s => s.Start).HasColumnName("start_time");
            slot.Property(s => s.End).HasColumnName("end_time");
            slot.Ignore(s => s.DurationHours);
            slot.Ignore(s => s.BufferedStartMinute);
            slot.Ignore(s => s.BufferedEndMinute);
        });

        // The range including the 1 h setup and 1 h cleanup buffers (BR-03). Generated by PostgreSQL, so no code can
        // forget or miscompute it; it feeds the exclusion constraint below.
        builder.Property<DateTime>("BufferedStart").HasColumnType("timestamp without time zone")
            .HasComputedColumnSql("(\"date\" + start_time) - interval '1 hour'", stored: true);
        builder.Property<DateTime>("BufferedEnd").HasColumnType("timestamp without time zone")
            .HasComputedColumnSql("(\"date\" + end_time) + interval '1 hour'", stored: true);

        builder.OwnsMany(x => x.EquipmentAllocations, equipment =>
        {
            equipment.ToTable("schedule_block_equipment");
            equipment.WithOwner().HasForeignKey("BlockId");
            equipment.Property<int>("Id");
            equipment.HasKey("Id");
            // Immutable value object: its read-only properties are bound through the private constructor.
            equipment.Property(e => e.Code).HasMaxLength(30);
            equipment.Property(e => e.Quantity);
        });
        builder.Navigation(x => x.EquipmentAllocations).HasField("_equipment").UsePropertyAccessMode(PropertyAccessMode.Field);

        // INV-19: at most one active block per event.
        builder.HasIndex(x => x.EventId)
            .IsUnique()
            .HasFilter("status = 'Active'")
            .HasDatabaseName("ux_schedule_blocks_inv19_one_active_block_per_event");
    }
}
